ENV_PY = textwrap.dedent(
    """
    from alembic import context
    from sqlalchemy import create_engine

    config = context.config
    metadata = config.attributes["metadata"]
    url = config.get_main_option("sqlalchemy.url")
    options = {"target_metadata": metadata, "compare_type": True,
               "compare_server_default": True}

    if context.is_offline_mode():
        context.configure(url=url, literal_binds=True, **options)
        with context.begin_transaction():
            context.run_migrations()
    else:
        engine = create_engine(url)
        with engine.connect() as connection:
            context.configure(connection=connection, **options)
            with context.begin_transaction():
                context.run_migrations()
        engine.dispose()
    """
)


def _metadata(version: int) -> MetaData:
    metadata = MetaData()
    columns = [
        Column("id", Integer, primary_key=True),
        Column("email", String, nullable=False, unique=True, comment="login"),
        Column("created_at", DateTime, server_default=func.now()),
        Column("price", Numeric(10, 2), server_default="1.50"),
        Column("profile", Struct({"city": String, "zip": Integer})),
        Column("tags", Map(String, Integer)),
        Column("history", ARRAY(Struct({"at": DateTime, "v": Integer}))),
        Column("ratio", Float(precision=24)),
        Column("mood", Enum("sad", "ok", name="mood")),
        # DuckDB reports these named ENUMs by their labels
        Column("moods", ARRAY(Enum("sad", "ok", name="mood"))),
        Column("last_visit", Struct({"mood": Enum("sad", "ok", name="mood")})),
        Column("status", Enum("on", "off")),
        # DuckDB stores these as UTINYINT, UINTEGER and UBIGINT
        Column("retries", UInt8),
        Column("visits", UInt32),
        Column("bytes_sent", UInt64),
    ]
    if version >= 2:
        columns.append(Column("nickname", String))
    users = Table("users", metadata, *columns, comment="app users")
    if version >= 2:
        # The downgrade drops this index, then its column, in one transaction.
        Index("ix_users_nickname", users.c.nickname)
        audit = Table(
            "audit",
            metadata,
            Column("id", Integer, primary_key=True),
            Column("action", String, nullable=False),
        )
        Index("ix_audit_action", audit.c.action)
    return metadata


def _config(tmp_path: Path, db_path: Path, version: int) -> Config:
    config = Config(str(tmp_path / "alembic.ini"))
    config.set_main_option("script_location", str(tmp_path / "migrations"))
    config.set_main_option("sqlalchemy.url", f"duckdb:///{db_path.as_posix()}")
    config.attributes["metadata"] = _metadata(version)
    return config


def test_autogenerate_upgrade_check_and_downgrade(
    tmp_path: Path, db_path: Path, make_engine: EngineFactory
) -> None:
    v1 = _config(tmp_path, db_path, 1)
    command.init(v1, str(tmp_path / "migrations"))
    (tmp_path / "migrations" / "env.py").write_text(ENV_PY)

    command.revision(v1, "create users", autogenerate=True, rev_id="v1")
    command.upgrade(v1, "head")
    command.check(v1)  # the rendered migration reproduces the metadata

    engine = make_engine(db_path)
    with engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO users (id, email, profile, tags, history) VALUES "
                "(1, 'a@x', {'city': 'Rome', 'zip': 1}, MAP {'k': 1}, "
                "[{'at': TIMESTAMP '2026-01-01', 'v': 2}])"
            )
        )
    engine.dispose()

    v2 = _config(tmp_path, db_path, 2)
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(v2)
    command.revision(v2, "add nickname", autogenerate=True, rev_id="v2")
    command.upgrade(v2, "head")
    command.check(v2)

    inspector = inspect(engine)
    assert "nickname" in {c["name"] for c in inspector.get_columns("users")}
    assert [i["name"] for i in inspector.get_indexes("users")] == ["ix_users_nickname"]
    assert [i["name"] for i in inspector.get_indexes("audit")] == ["ix_audit_action"]
    with engine.connect() as conn:
        assert conn.execute(text("SELECT profile.city FROM users")).scalar() == "Rome"

    command.downgrade(v2, "-1")
    inspector = inspect(engine)
    assert "nickname" not in {c["name"] for c in inspector.get_columns("users")}
    assert not inspector.has_table("audit")
    with engine.connect() as conn:
        # Data written before the second revision survives its round trip.
        assert conn.execute(text("SELECT email FROM users")).scalar() == "a@x"

    command.downgrade(v1, "base")
    assert inspect(engine).get_table_names() == ["alembic_version"]


def test_offline_upgrade_renders_executable_sql(
    tmp_path: Path, db_path: Path, make_engine: EngineFactory
) -> None:
    config = _config(tmp_path, db_path, 2)
    command.init(config, str(tmp_path / "migrations"))
    (tmp_path / "migrations" / "env.py").write_text(ENV_PY)
    command.revision(config, "all", autogenerate=True, rev_id="v1")

    buffer = io.StringIO()
    config.output_buffer = buffer
    command.upgrade(config, "head", sql=True)
    script = buffer.getvalue()
    assert "CREATE TABLE users" in script

    # The offline script runs as-is on a fresh database. It manages its own
    # transaction, so run it outside SQLAlchemy's.
    engine = make_engine(tmp_path / "offline.duckdb")
    with engine.connect() as conn:
        autocommit = conn.execution_options(isolation_level="AUTOCOMMIT")
        autocommit.exec_driver_sql(script)
    assert {"users", "audit", "alembic_version"} <= set(
        inspect(engine).get_table_names()
    )


@pytest.mark.parametrize(
    "operation, columns, indexes",
    [
        (
            lambda op: (
                op.drop_index("ix_users_n", table_name="users"),
                op.drop_column("users", "n"),
            ),
            ["id", "n2", "extra"],
            {"ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.drop_column("users", "n"),
            ["id", "n2", "extra"],
            {"ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.drop_column("users", "extra"),
            ["id", "n", "n2"],
            {"ix_users_n": ["n"], "ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.alter_column("users", "n", new_column_name="nick"),
            ["id", "nick", "n2", "extra"],
            {"ix_users_n": ["nick"], "ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.alter_column(
                "users",
                "extra",
                type_=BigInteger,
                existing_type=Integer,
                nullable=False,
            ),
            ["id", "n", "n2", "extra"],
            {"ix_users_n": ["n"], "ix_users_n2": ["n2"]},
        ),
    ],
    ids=[
        "drop-index-then-column",
        "drop-indexed",
        "drop-other",
        "rename",
        "type-and-null",
    ],
)
def test_alter_operations_on_indexed_tables(
    operation, columns, indexes, make_engine: EngineFactory
) -> None:
    # DuckDB rejects these ALTERs while the table has any index, even after
    # DROP INDEX in the same transaction. DuckDBImpl recreates the table.
    from alembic.migration import MigrationContext
    from alembic.operations import Operations

    engine = make_engine("duckdb:///:memory:")
    with engine.begin() as conn:
        conn.execute(
            text(
                "CREATE TABLE users (id INTEGER PRIMARY KEY, n VARCHAR, n2 VARCHAR UNIQUE, extra INTEGER)"
            )
        )
        conn.execute(text("CREATE INDEX ix_users_n ON users (n)"))
        conn.execute(text("CREATE INDEX ix_users_n2 ON users (n2)"))
        conn.execute(text("INSERT INTO users VALUES (1, 'a', 'b', 5)"))
    with engine.begin() as conn:
        operation(Operations(MigrationContext.configure(conn)))

    inspector = inspect(engine)
    assert [c["name"] for c in inspector.get_columns("users")] == columns
    assert {
        i["name"]: i["column_names"] for i in inspector.get_indexes("users")
    } == indexes
    assert [u["column_names"] for u in inspector.get_unique_constraints("users")] == [
        ["n2"]
    ]
    with engine.connect() as conn:
        row = conn.execute(text("SELECT * FROM users")).mappings().one()
    assert row["id"] == 1 and row.get("n2") == "b"


def test_drop_column_without_indexes_stays_a_plain_alter(
    make_engine: EngineFactory,
) -> None:
    from alembic.migration import MigrationContext
    from alembic.operations import Operations

    engine = make_engine("duckdb:///:memory:")
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE t (id INTEGER, gone INTEGER)"))
        statements: list = []
        event.listen(conn, "before_cursor_execute", lambda *a: statements.append(a[2]))
        Operations(MigrationContext.configure(conn)).drop_column("t", "gone")
    assert any(s.startswith("ALTER TABLE t DROP COLUMN gone") for s in statements)
    assert not any("_alembic_tmp" in s for s in statements)
    assert [c["name"] for c in inspect(engine).get_columns("t")] == ["id"]

    # Offline scripts cannot reflect indexes and keep the plain statement.
    buffer = io.StringIO()
    context = MigrationContext.configure(
        dialect_name="duckdb", opts={"as_sql": True, "output_buffer": buffer}
    )
    Operations(context).drop_column("t", "gone")
    assert "ALTER TABLE t DROP COLUMN gone" in buffer.getvalue()


def _supports_time_ns() -> bool:
    try:
        duckdb.sql("SELECT CAST(NULL AS TIME_NS)")
    except duckdb.Error:
        return False
    return True


def test_autogenerate_imports_datatypes_for_scalar_and_nested_array_types(
    tmp_path: Path, db_path: Path
) -> None:
    metadata = MetaData()
    columns = [
        Column("id", Integer, primary_key=True),
        Column("flags", UInt64),
        Column("big", HugeInteger),
        Column("ts_ns", TimestampNs),
        Column("arr_big", ARRAY(HugeInteger)),
        Column("matrix", ARRAY(FixedArray(Struct({"a": Integer}), 2))),
        Column("fixed_list", FixedArray(ARRAY(HugeInteger), 2)),
    ]
    if _supports_time_ns():
        columns.append(Column("tm_ns", TimeNs))
    Table("telemetry", metadata, *columns)

    config = Config(str(tmp_path / "alembic.ini"))
    config.set_main_option("script_location", str(tmp_path / "migrations"))
    config.set_main_option("sqlalchemy.url", f"duckdb:///{db_path.as_posix()}")
    config.attributes["metadata"] = metadata

    command.init(config, str(tmp_path / "migrations"))
    (tmp_path / "migrations" / "env.py").write_text(ENV_PY)
    command.revision(config, "create telemetry", autogenerate=True, rev_id="v1")

    script_dir = tmp_path / "migrations" / "versions"
    script_text = next(script_dir.glob("v1_*.py")).read_text()
    assert "import duckdb_sqlalchemy.datatypes" in script_text

    command.upgrade(config, "head")
    command.check(config)

    if Version(duckdb.__version__) >= Version("1.5.0"):
        from alembic.autogenerate.api import AutogenContext
        from alembic.autogenerate.render import _repr_type
        from alembic.migration import MigrationContext

        mc = MigrationContext.configure(
            dialect_name="duckdb",
            opts={"sqlalchemy_module_prefix": "sa.", "user_module_prefix": None},
        )
        ac = AutogenContext(mc)
        assert _repr_type(Variant(), ac) == "duckdb_sqlalchemy.datatypes.Variant()"
        assert "import duckdb_sqlalchemy.datatypes" in ac.imports


def _autogenerate_diffs(engine: Engine, metadata: MetaData, **opts: object) -> list:
    with engine.connect() as conn:
        context = MigrationContext.configure(conn, opts={"compare_type": True, **opts})
        return compare_metadata(context, metadata)


def test_include_schemas_compares_the_current_schema_once(
    make_engine: EngineFactory, db_path: Path
) -> None:
    # get_schema_names() reports the current schema as "app.main". Alembic
    # compared it as that name too and proposed dropping its tables.
    engine = make_engine(db_path)
    metadata = MetaData()
    Table("users", metadata, Column("id", Integer, primary_key=True))
    metadata.create_all(engine)
    with engine.begin() as conn:
        conn.execute(text("CREATE SCHEMA analytics"))
        conn.execute(text("CREATE TABLE analytics.events (id INTEGER)"))

    diffs = _autogenerate_diffs(engine, metadata, include_schemas=True)

    # Other schemas are still compared: the model has no analytics.events.
    assert [(op, table.schema, table.name) for op, table in diffs] == [
        ("remove_table", "app.analytics", "events")
    ]
    assert "app.main" in inspect(engine).get_schema_names()


@pytest.mark.parametrize("index", [None, "table", "column"])
def test_add_not_null_column(
    index: object, make_engine: EngineFactory, db_path: Path
) -> None:
    # DuckDB 1.x rejects ADD COLUMN ... NOT NULL, and DuckDB 2.x rejects it
    # on a table with an index. DuckDBImpl recreates the table.
    engine = make_engine(db_path)
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE t (id INTEGER, name VARCHAR)"))
        if index == "table":
            conn.execute(text("CREATE INDEX ix_t_name ON t (name)"))
        conn.execute(text("INSERT INTO t VALUES (1, 'a')"))
    with engine.begin() as conn:
        Operations(MigrationContext.configure(conn)).add_column(
            "t",
            Column(
                "active",
                Boolean,
                server_default=false(),
                nullable=False,
                index=index == "column",
                comment="enabled",
            ),
        )

    inspector = inspect(engine)
    active = inspector.get_columns("t")[-1]
    assert (active["name"], active["nullable"], active["comment"]) == (
        "active",
        False,
        "enabled",
    )
    expected_indexes = {None: [], "table": ["ix_t_name"], "column": ["ix_t_active"]}
    assert [i["name"] for i in inspector.get_indexes("t")] == expected_indexes[index]
    with engine.connect() as conn:
        assert conn.execute(text("SELECT * FROM t")).all() == [(1, "a", False)]


def test_autogenerate_compares_nested_members_like_columns(
    make_engine: EngineFactory, db_path: Path
) -> None:
    engine = make_engine(db_path)
    metadata = MetaData()
    Table(
        "t",
        metadata,
        Column("s", Struct({"a": String(50), "b": Numeric})),
        Column("m", Map(String(10), UInt32)),
        Column("f", FixedArray(Float(24), 3)),
        Column("l", ARRAY(Struct({"a": Text}))),
    )
    metadata.create_all(engine)

    # STRUCT(a VARCHAR, b DECIMAL(18,3)), MAP(VARCHAR, UINTEGER), FLOAT[3]
    # and STRUCT(a VARCHAR)[] are what these members create.
    assert _autogenerate_diffs(engine, metadata) == []

    changed = MetaData()
    Table(
        "t",
        changed,
        Column("s", Struct({"a": String(50), "b": Numeric, "c": Integer})),
        Column("m", Map(String(10), BigInteger)),
        Column("f", FixedArray(Float(24), 4)),
        Column("l", ARRAY(Struct({"a": Integer}))),
    )
    diffs = _autogenerate_diffs(engine, changed)
    assert sorted((d[0][0], d[0][3]) for d in diffs) == [
        ("modify_type", name) for name in ("f", "l", "m", "s")
    ]


def test_autogenerate_compares_expression_indexes(
    make_engine: EngineFactory, db_path: Path
) -> None:
    engine = make_engine(db_path)
    metadata = MetaData()
    users = Table("users", metadata, Column("id", Integer), Column("email", String))
    Index("ix_users_email", func.lower(users.c.email))
    Index("ix_users_email_id", func.lower(users.c.email), users.c.id, unique=True)
    metadata.create_all(engine)

    assert _autogenerate_diffs(engine, metadata) == []

    changed = MetaData()
    users = Table("users", changed, Column("id", Integer), Column("email", String))
    Index("ix_users_email", func.upper(users.c.email))
    Index("ix_users_email_id", func.lower(users.c.email), users.c.id)
    diffs = _autogenerate_diffs(engine, changed)
    assert sorted((op, index.name) for op, index in diffs) == [
        ("add_index", "ix_users_email"),
        ("add_index", "ix_users_email_id"),
        ("remove_index", "ix_users_email"),
        ("remove_index", "ix_users_email_id"),
    ]


def test_recreating_a_table_keeps_its_generated_columns(
    make_engine: EngineFactory, db_path: Path
) -> None:
    engine = make_engine(db_path)
    with engine.begin() as conn:
        conn.execute(
            text(
                "CREATE TABLE items (id INTEGER, qty INTEGER, "
                "total INTEGER GENERATED ALWAYS AS (qty * 2), note VARCHAR)"
            )
        )
        conn.execute(text("CREATE INDEX ix_items_id ON items (id)"))
        conn.execute(text("INSERT INTO items (id, qty, note) VALUES (1, 3, 'n')"))
    with engine.begin() as conn:
        op = Operations(MigrationContext.configure(conn))
        op.drop_column("items", "note")  # the index makes this a recreate
        with op.batch_alter_table("items", recreate="always") as batch:
            batch.create_unique_constraint("uq_items_id", ["id"])

    inspector = inspect(engine)
    columns = {c["name"]: c for c in inspector.get_columns("items")}
    assert list(columns) == ["id", "qty", "total"]
    assert columns["total"]["computed"]["sqltext"] == "(qty * 2)"
    assert [u["column_names"] for u in inspector.get_unique_constraints("items")] == [
        ["id"]
    ]
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO items (id, qty) VALUES (2, 5)"))
        assert conn.execute(text("SELECT * FROM items ORDER BY id")).all() == [
            (1, 3, 6),
            (2, 5, 10),
        ]


def test_drop_column_drops_expression_indexes_that_use_it(
    make_engine: EngineFactory, db_path: Path
) -> None:
    engine = make_engine(db_path)
    with engine.begin() as conn:
        conn.execute(
            text('CREATE TABLE users (id INTEGER, "Email" VARCHAR, name VARCHAR)')
        )
        conn.execute(text('CREATE INDEX ix_users_email ON users (lower("Email"))'))
        # Mentions Email only in a string literal, so it stays.
        conn.execute(
            text("CREATE INDEX ix_users_name ON users (coalesce(name, 'Email'), id)")
        )
        conn.execute(text("INSERT INTO users VALUES (1, 'A@x', 'a')"))
    with engine.begin() as conn:
        Operations(MigrationContext.configure(conn)).drop_column("users", "Email")

    inspector = inspect(engine)
    assert [c["name"] for c in inspector.get_columns("users")] == ["id", "name"]
    assert [i["name"] for i in inspector.get_indexes("users")] == ["ix_users_name"]
    with engine.connect() as conn:
        assert conn.execute(text("SELECT * FROM users")).all() == [(1, "a")]
