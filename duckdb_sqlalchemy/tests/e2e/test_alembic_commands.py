ENV_PY = textwrap.dedent(
    """
    from alembic import context
    from sqlalchemy import create_engine

    config = context.config
    metadata = config.attributes["metadata"]
    url = config.get_main_option("sqlalchemy.url")
    options = {"target_metadata": metadata, "compare_type": True,
               "compare_server_default": True}

    if context.is_offline_mode():
        context.configure(url=url, literal_binds=True, **options)
        with context.begin_transaction():
            context.run_migrations()
    else:
        engine = create_engine(url)
        with engine.connect() as connection:
            context.configure(connection=connection, **options)
            with context.begin_transaction():
                context.run_migrations()
        engine.dispose()
    """
)


def _metadata(version: int) -> MetaData:
    metadata = MetaData()
    columns = [
        Column("id", Integer, primary_key=True),
        Column("email", String, nullable=False, unique=True, comment="login"),
        Column("created_at", DateTime, server_default=func.now()),
        Column("price", Numeric(10, 2), server_default="1.50"),
        Column("profile", Struct({"city": String, "zip": Integer})),
        Column("tags", Map(String, Integer)),
        Column("history", ARRAY(Struct({"at": DateTime, "v": Integer}))),
        Column("ratio", Float(precision=24)),
        Column("mood", Enum("sad", "ok", name="mood")),
        Column("status", Enum("on", "off")),
    ]
    if version >= 2:
        columns.append(Column("nickname", String))
    users = Table("users", metadata, *columns, comment="app users")
    if version >= 2:
        # The downgrade drops this index, then its column, in one transaction.
        Index("ix_users_nickname", users.c.nickname)
        audit = Table(
            "audit",
            metadata,
            Column("id", Integer, primary_key=True),
            Column("action", String, nullable=False),
        )
        Index("ix_audit_action", audit.c.action)
    return metadata


def _config(tmp_path: Path, db_path: Path, version: int) -> Config:
    config = Config(str(tmp_path / "alembic.ini"))
    config.set_main_option("script_location", str(tmp_path / "migrations"))
    config.set_main_option("sqlalchemy.url", f"duckdb:///{db_path.as_posix()}")
    config.attributes["metadata"] = _metadata(version)
    return config


def test_autogenerate_upgrade_check_and_downgrade(
    tmp_path: Path, db_path: Path, make_engine: EngineFactory
) -> None:
    v1 = _config(tmp_path, db_path, 1)
    command.init(v1, str(tmp_path / "migrations"))
    (tmp_path / "migrations" / "env.py").write_text(ENV_PY)

    command.revision(v1, "create users", autogenerate=True, rev_id="v1")
    command.upgrade(v1, "head")
    command.check(v1)  # the rendered migration reproduces the metadata

    engine = make_engine(db_path)
    with engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO users (id, email, profile, tags, history) VALUES "
                "(1, 'a@x', {'city': 'Rome', 'zip': 1}, MAP {'k': 1}, "
                "[{'at': TIMESTAMP '2026-01-01', 'v': 2}])"
            )
        )
    engine.dispose()

    v2 = _config(tmp_path, db_path, 2)
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(v2)
    command.revision(v2, "add nickname", autogenerate=True, rev_id="v2")
    command.upgrade(v2, "head")
    command.check(v2)

    inspector = inspect(engine)
    assert "nickname" in {c["name"] for c in inspector.get_columns("users")}
    assert [i["name"] for i in inspector.get_indexes("users")] == ["ix_users_nickname"]
    assert [i["name"] for i in inspector.get_indexes("audit")] == ["ix_audit_action"]
    with engine.connect() as conn:
        assert conn.execute(text("SELECT profile.city FROM users")).scalar() == "Rome"

    command.downgrade(v2, "-1")
    inspector = inspect(engine)
    assert "nickname" not in {c["name"] for c in inspector.get_columns("users")}
    assert not inspector.has_table("audit")
    with engine.connect() as conn:
        # Data written before the second revision survives its round trip.
        assert conn.execute(text("SELECT email FROM users")).scalar() == "a@x"

    command.downgrade(v1, "base")
    assert inspect(engine).get_table_names() == ["alembic_version"]


def test_offline_upgrade_renders_executable_sql(
    tmp_path: Path, db_path: Path, make_engine: EngineFactory
) -> None:
    config = _config(tmp_path, db_path, 2)
    command.init(config, str(tmp_path / "migrations"))
    (tmp_path / "migrations" / "env.py").write_text(ENV_PY)
    command.revision(config, "all", autogenerate=True, rev_id="v1")

    buffer = io.StringIO()
    config.output_buffer = buffer
    command.upgrade(config, "head", sql=True)
    script = buffer.getvalue()
    assert "CREATE TABLE users" in script

    # The offline script runs as-is on a fresh database. It manages its own
    # transaction, so run it outside SQLAlchemy's.
    engine = make_engine(tmp_path / "offline.duckdb")
    with engine.connect() as conn:
        autocommit = conn.execution_options(isolation_level="AUTOCOMMIT")
        autocommit.exec_driver_sql(script)
    assert {"users", "audit", "alembic_version"} <= set(
        inspect(engine).get_table_names()
    )


@pytest.mark.parametrize(
    "operation, columns, indexes",
    [
        (
            lambda op: (
                op.drop_index("ix_users_n", table_name="users"),
                op.drop_column("users", "n"),
            ),
            ["id", "n2", "extra"],
            {"ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.drop_column("users", "n"),
            ["id", "n2", "extra"],
            {"ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.drop_column("users", "extra"),
            ["id", "n", "n2"],
            {"ix_users_n": ["n"], "ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.alter_column("users", "n", new_column_name="nick"),
            ["id", "nick", "n2", "extra"],
            {"ix_users_n": ["nick"], "ix_users_n2": ["n2"]},
        ),
        (
            lambda op: op.alter_column(
                "users",
                "extra",
                type_=BigInteger,
                existing_type=Integer,
                nullable=False,
            ),
            ["id", "n", "n2", "extra"],
            {"ix_users_n": ["n"], "ix_users_n2": ["n2"]},
        ),
    ],
    ids=[
        "drop-index-then-column",
        "drop-indexed",
        "drop-other",
        "rename",
        "type-and-null",
    ],
)
def test_alter_operations_on_indexed_tables(
    operation, columns, indexes, make_engine: EngineFactory
) -> None:
    # DuckDB rejects these ALTERs while the table has any index, even after
    # DROP INDEX in the same transaction. DuckDBImpl recreates the table.
    from alembic.migration import MigrationContext
    from alembic.operations import Operations

    engine = make_engine("duckdb:///:memory:")
    with engine.begin() as conn:
        conn.execute(
            text(
                "CREATE TABLE users (id INTEGER PRIMARY KEY, n VARCHAR, n2 VARCHAR UNIQUE, extra INTEGER)"
            )
        )
        conn.execute(text("CREATE INDEX ix_users_n ON users (n)"))
        conn.execute(text("CREATE INDEX ix_users_n2 ON users (n2)"))
        conn.execute(text("INSERT INTO users VALUES (1, 'a', 'b', 5)"))
    with engine.begin() as conn:
        operation(Operations(MigrationContext.configure(conn)))

    inspector = inspect(engine)
    assert [c["name"] for c in inspector.get_columns("users")] == columns
    assert {
        i["name"]: i["column_names"] for i in inspector.get_indexes("users")
    } == indexes
    assert [u["column_names"] for u in inspector.get_unique_constraints("users")] == [
        ["n2"]
    ]
    with engine.connect() as conn:
        row = conn.execute(text("SELECT * FROM users")).mappings().one()
    assert row["id"] == 1 and row.get("n2") == "b"


def test_drop_column_without_indexes_stays_a_plain_alter(
    make_engine: EngineFactory,
) -> None:
    from alembic.migration import MigrationContext
    from alembic.operations import Operations

    engine = make_engine("duckdb:///:memory:")
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE t (id INTEGER, gone INTEGER)"))
        statements: list = []
        event.listen(conn, "before_cursor_execute", lambda *a: statements.append(a[2]))
        Operations(MigrationContext.configure(conn)).drop_column("t", "gone")
    assert any(s.startswith("ALTER TABLE t DROP COLUMN gone") for s in statements)
    assert not any("_alembic_tmp" in s for s in statements)
    assert [c["name"] for c in inspect(engine).get_columns("t")] == ["id"]

    # Offline scripts cannot reflect indexes and keep the plain statement.
    buffer = io.StringIO()
    context = MigrationContext.configure(
        dialect_name="duckdb", opts={"as_sql": True, "output_buffer": buffer}
    )
    Operations(context).drop_column("t", "gone")
    assert "ALTER TABLE t DROP COLUMN gone" in buffer.getvalue()
